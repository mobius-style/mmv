#!/usr/bin/env python3
"""Three figures for the v11 dataset cards / paper. Every number comes from the measurement logs."""
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt, numpy as np
from PIL import Image
OUT = "/home/happy/.codex/bench/wiki_forensics/fig_"

# 1. token length vs the 512 window
fig, ax = plt.subplots(figsize=(8, 4.2), dpi=200)
langs = ["EN", "JA", "ZH"]; old_over = [0.97, 17.26, 18.02]; new_over = [0.0, 0.0, 0.0]
x = np.arange(3); w = 0.36
ax.bar(x-w/2, old_over, w, color="#c62828", label="1,536-character slices (shipped 2026-04/06)")
ax.bar(x+w/2, new_over, w, color="#1565c0", label="256-token budget, sentence boundaries (v11)")
for i,(o,n) in enumerate(zip(old_over,new_over)):
    ax.text(i-w/2, o+0.4, f"{o:.1f}%", ha="center", fontsize=9)
    ax.text(i+w/2, 0.4, "0.00%", ha="center", fontsize=9, color="#1565c0")
ax.set_xticks(x); ax.set_xticklabels([f"{l}\n({c} chars/token)" for l,c in zip(langs,["4.3","2.33","2.06"])])
ax.set_ylabel("chunks exceeding the ME5 512-token window\n(the excess is silently truncated at embed time)", fontsize=9)
ax.set_title("A character-length cap breaks on CJK: one in five Chinese chunks was truncated", fontsize=10)
ax.legend(fontsize=8.5, frameon=False); ax.spines[["top","right"]].set_visible(False); ax.set_ylim(0, 22)
fig.text(0.01, 0.01, "Measured on the published datasets, 8,000 chunks/language. Truncation is silent: a long passage and the same passage plus a distinct tail embed to cosine 1.000000.", fontsize=6.5, color="#555")
plt.tight_layout(rect=(0,0.04,1,1)); fig.savefig(OUT+"v11_tokens.png"); Image.open(OUT+"v11_tokens.png").save(OUT+"v11_tokens.png")

# 2. index frontier: size vs end-to-end MRR
fig, ax = plt.subplots(figsize=(8, 4.6), dpi=200)
pts = [("IVF,PQ64\n(shipped)", 0.7, 61.4, 78.7, "#c62828"),
       ("OPQ256,IVF,PQ256", 2.8, 67.9, 87.5, "#ef6c00"),
       ("PCA512,IVF,SQ8", 5.6, 65.1, 86.8, "#9e9e9e"),
       ("IVF,SQ4  (v11)", 5.6, 68.6, 88.6, "#1565c0"),
       ("IVF,SQ8", 11.3, 68.7, 88.9, "#455a64")]
for name, gb, ja, en, c in pts:
    ax.scatter(gb, ja, s=120, color=c, zorder=3); ax.scatter(gb, en, s=120, color=c, marker="^", zorder=3)
    ax.annotate(name, (gb, ja), textcoords="offset points", xytext=(6, -14), fontsize=8, color=c)
ax.axhline(69.2, ls="--", lw=0.9, color="#333"); ax.text(11.6, 69.4, "exact search, ja (69.2)", fontsize=7.5, ha="right")
ax.axhline(89.4, ls="--", lw=0.9, color="#333"); ax.text(11.6, 89.6, "exact search, en (89.4)", fontsize=7.5, ha="right")
ax.set_xlabel("index size for the English corpus (GB)"); ax.set_ylabel("MRR on generated content questions\n(● Japanese  ▲ English)", fontsize=9)
ax.set_title("Product quantisation is the wrong trade for ME5 vectors", fontsize=10)
ax.set_xlim(0, 12.5); ax.set_ylim(58, 93); ax.spines[["top","right"]].set_visible(False)
fig.text(0.01, 0.01, "ja: 205,789 chunks / 303 questions · en: 158,200 chunks / 400 questions · nprobe 128 · questions generated by a local 26B from each article, titles withheld.", fontsize=6.5, color="#555")
plt.tight_layout(rect=(0,0.04,1,1)); fig.savefig(OUT+"v11_index.png"); Image.open(OUT+"v11_index.png").save(OUT+"v11_index.png")
print("figures 1-2 written")
